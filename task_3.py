
while True:                 #While loop to keep the conversation going
    user = input("You: ")               #Get user input for the conversation
    if user =="hello":                  #If the user says hello, the program responds with a greeting
        print ("Hi")
    elif user=="How are you?":          #If the user asks how the program is doing, it responds with a polite answer
        print("I'm fine, thank you!")
    elif user=="bye":                   #If the user says bye, the program responds with a goodbye message and exits the loop
        print("Goodbye!")
    else:                                #If the user says something that the program doesn't understand, it responds with a message indicating that it doesn't understand.
        print("I don't understand that.")







